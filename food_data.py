def lookup(food_name: str, extra: dict = None):
    """extra: dict opcional {nome_em_minusculas: (kcal, proteina_g, hidratos_g, gordura_g)}
    com alimentos personalizados do utilizador, verificados primeiro."""
    key = food_name.strip().lower()
    if extra and key in extra:
        return extra[key]
    if key in FOODS:
        return FOODS[key]
    # tenta correspondência parcial
    for name, vals in FOODS.items():
        if name in key or key in name:
            return vals
    if extra:
        for name, vals in extra.items():
            if name in key or key in name:
                return vals
    return None


def portion_grams(food_name: str):
    """Gramas para '1 dose'/'1 porção' deste alimento (usa um valor por
    omissão se o alimento não estiver na lista)."""
    key = food_name.strip().lower()
    if key in PORTION_G_DEFAULTS:
        return PORTION_G_DEFAULTS[key]
    for name, grams in PORTION_G_DEFAULTS.items():
        if name in key or key in name:
            return grams
    return PORTION_G_PADRAO


